def haversine_km(lat1: float, lon1: float, lat2: float, lon2: float) -> float:
    phi1, phi2 = math.radians(lat1), math.radians(lat2)
    delta_phi = math.radians(lat2 - lat1)
    delta_lambda = math.radians(lon2 - lon1)
    a = math.sin(delta_phi / 2.0)**2 + math.cos(phi1) * math.cos(phi2) * math.sin(delta_lambda / 2.0)**2
    return 6371.0088 * 2.0 * math.atan2(math.sqrt(a), math.sqrt(1.0 - a))

def find_nearest_assets(lat: float, lon: float, top_k: int = 3) -> List[Dict[str, Any]]:
    if assets_df is None or assets_df.empty:
        return []
    scored = []
    for _, row in assets_df.iterrows():
        try:
            a_lat, a_lon = float(row["latitude"]), float(row["longitude"])
            if math.isnan(a_lat) or math.isnan(a_lon):
                continue
            d = haversine_km(lat, lon, a_lat, a_lon)
            # Clean NaN float values from row dict to ensure JSON compliance
            row_dict = {}
            for k, v in row.to_dict().items():
                if isinstance(v, float) and (math.isnan(v) or math.isinf(v)):
                    row_dict[k] = None
                else:
                    row_dict[k] = v
            scored.append((d, row_dict))
        except Exception:
            continue
    scored.sort(key=lambda x: x[0])
    return [{"distance_km": round(d, 3), **item} for d, item in scored[:top_k]]

