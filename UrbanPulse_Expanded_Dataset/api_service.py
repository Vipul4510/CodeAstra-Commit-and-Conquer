def evaluate_pairwise_with_ml(evt1: Dict[str, Any], evt2: Dict[str, Any]) -> Dict[str, Any]:
    """Runs the trained LightGBM CalibratedClassifierCV on a pair of events."""
    id1 = evt1.get("observation_id", "EVT-1")
    id2 = evt2.get("observation_id", "EVT-2")

    lat1, lon1 = float(evt1["latitude"]), float(evt1["longitude"])
    lat2, lon2 = float(evt2["latitude"]), float(evt2["longitude"])
    geo_dist = haversine_km(lat1, lon1, lat2, lon2)

    # Time diff in minutes
    try:
        t1 = datetime.fromisoformat(evt1.get("observation_time", "").replace("Z", "+00:00"))
        t2 = datetime.fromisoformat(evt2.get("observation_time", "").replace("Z", "+00:00"))
        time_diff = abs((t1 - t2).total_seconds()) / 60.0
    except Exception:
        time_diff = 5.0

    txt1 = evt1.get("text", "")
    txt2 = evt2.get("text", "")
    words1 = set(txt1.lower().split())
    words2 = set(txt2.lower().split())
    jaccard = len(words1 & words2) / max(len(words1 | words2), 1)

    same_loc = 1.0 if evt1.get("locality") == evt2.get("locality") else 0.0
    same_src = 1.0 if evt1.get("modality") == evt2.get("modality") else 0.0

    df_pairs = pd.DataFrame([{
        "pair_id": f"PAIR-{id1}-{id2}",
        "observation_id_a": id1,
        "observation_id_b": id2,
        "geo_distance_km": geo_dist,
        "time_diff_minutes": time_diff,
        "text_similarity": jaccard,
        "same_locality": same_loc,
        "same_source": same_src,
        "reliability_product": 0.81,
    }])

    obs_records = {
        id1: {
            "observation_id": id1,
            "source_type": evt1.get("modality", "SENSOR"),
            "event_type": evt1.get("event_type", "ROAD_WATERLOGGING"),
            "location_accuracy_m": 25.0,
            "source_reliability_score": 0.90,
            "verification_status": "VERIFIED",
            "is_duplicate_candidate": False,
            "text_original": txt1,
        },
        id2: {
            "observation_id": id2,
            "source_type": evt2.get("modality", "SENSOR"),
            "event_type": evt2.get("event_type", "ROAD_WATERLOGGING"),
            "location_accuracy_m": 25.0,
            "source_reliability_score": 0.90,
            "verification_status": "VERIFIED",
            "is_duplicate_candidate": False,
            "text_original": txt2,
        }
    }
    obs_df = pd.DataFrame.from_dict(obs_records, orient="index")

    feature_extractor = PairwiseFeatureExtractor()
    features_df = feature_extractor.extract_features(df_pairs, obs_df=obs_df)
    feature_names = ml_artifacts["feature_names"]

    X = features_df[feature_names].values
    X_scaled = ml_artifacts["scaler"].transform(X)

    model = ml_artifacts["model"]
    probs = model.predict_proba(X_scaled)[0]
    pred_idx = int(model.predict(X_scaled)[0])
    pred_label = ml_artifacts["label_encoder"].inverse_transform([pred_idx])[0]
    conf = float(probs[pred_idx])

    return {
        "predicted_relationship": pred_label,
        "confidence": round(conf, 4),
        "class_probabilities": {
            cls_name: round(float(p), 4)
            for cls_name, p in zip(ml_artifacts["target_classes"], probs)
        }
    }

