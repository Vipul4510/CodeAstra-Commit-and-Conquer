# Action Recommendation Generator based on Model Inference
# ------------------------------------------------------------------------------
def generate_location_response_plan(
    lat: float,
    lon: float,
    locality: str,
    event_type: str,
    ml_relationship: Optional[str],
    ml_confidence: float,
    nearest_assets: List[Dict[str, Any]],
    water_level_cm: Optional[float] = None,
    power_status: Optional[str] = None,
    traffic_data: Optional[Dict[str, Any]] = None
) -> Dict[str, Any]:
    """Synthesizes physical dependency constraints, ML relationship, traffic impact, and coordinates into actionable response."""
    actions = []
    alert_level = "GREEN_NORMAL"
    urgency = "LOW"
    root_cause_hypothesis = "Normal runoff"

    traffic_data = traffic_data or {}
    speed_drop = traffic_data.get("speed_drop_pct")
    passability = traffic_data.get("road_passability", "PASSABLE")
    delay_min = traffic_data.get("traffic_delay_minutes", 0.0)
    route_id = traffic_data.get("affected_route_id")

    # Evaluate severity
    is_waterlog = "WATERLOG" in event_type.upper() or "FLOOD" in event_type.upper() or (water_level_cm and water_level_cm >= 25)
    is_critical_water = (water_level_cm and water_level_cm >= 50) or "CRITICAL" in event_type.upper()
    is_power_out = power_status == "OUTAGE" or "POWER" in event_type.upper()
    is_traffic_jam = (speed_drop is not None and speed_drop >= 40) or passability in ("RESTRICTED", "IMPASSABLE", "CLOSED") or (delay_min and delay_min >= 20)

    if is_critical_water or passability == "CLOSED":
        alert_level = "RED_CRITICAL"
        urgency = "IMMEDIATE"
        actions.append(f"Deploy mobile de-watering high-capacity pumps to coordinates ({lat:.4f}, {lon:.4f}).")
        actions.append(f"Issue traffic diversion and close underpasses/subways around {locality}.")
        root_cause_hypothesis = "Drainage capacity exceeded or downstream blockage causing roadway closure"
    elif is_waterlog or is_traffic_jam:
        alert_level = "AMBER_WARNING"
        urgency = "HIGH"
        actions.append(f"Dispatch Municipal Ward field inspection team to {locality}.")
        actions.append(f"Clear stormwater outfall grates and inspect manhole sumps.")
        root_cause_hypothesis = "Localized runoff accumulation impeding vehicular movement"

    if is_power_out:
        alert_level = "RED_CRITICAL" if (is_waterlog or is_traffic_jam) else "AMBER_WARNING"
        urgency = "IMMEDIATE" if is_waterlog else "HIGH"
        actions.append(f"Switch adjacent pumping stations in {locality} to secondary diesel generation (DG set).")
        root_cause_hypothesis = "Pumping failure triggered by power feeder disruption"

    # Traffic specific recommendations
    traffic_summary = {
        "passability": passability,
        "speed_drop_pct": speed_drop,
        "delay_minutes": delay_min,
        "affected_route_id": route_id
    }
    if is_traffic_jam:
        actions.append(f"Broadcast digital message signs (VMS) on corridor: {delay_min} min delay near {locality}.")
        if route_id:
            actions.append(f"Activate alternative bypass detour for {route_id} to avoid bottleneck.")
        actions.append(f"Deploy traffic marshals to intersections feeding ({lat:.4f}, {lon:.4f}).")

    if nearest_assets:
        top_ast = nearest_assets[0]
        ast_id = top_ast.get("asset_id", "UNKNOWN")
        ast_type = top_ast.get("asset_type", "ASSET")
        actions.append(f"Inspect priority asset {ast_id} ({ast_type}) located {top_ast.get('distance_km')}km away.")

    return {
        "alert_level": alert_level,
        "urgency": urgency,
        "root_cause_hypothesis": root_cause_hypothesis,
        "traffic_impact": traffic_summary,
        "ml_inference_context": {
            "predicted_relationship": ml_relationship or "INITIAL_OBSERVATION",
            "model_confidence": ml_confidence
        },
        "recommended_actions": actions,
        "dispatch_units": [
            f"Disaster Management Cell - Ward ({locality})",
            "Stormwater Drainage (SWD) Response Crew",
            "Traffic Police Control Division (BTP/MTP)",
            "Public Transit & Bus Operations Control"
        ]
    }

